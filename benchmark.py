"""
Purpose
-------
Headless benchmark that measures the latency and throughput of every pipeline
stage (ASR, LLM, TTS) plus a full end-to-end utterance, without needing a
microphone or speaker.

Rationale
---------
The voice pipeline is distributed across threaded workers, so latency appears
in several places: speech-to-text, first LLM token, tokens/sec, TTS synthesis
(real-time factor), and the total E2E time from audio to first spoken syllable.
This benchmark quantifies each one on the current machine so the numbers can be
tracked over time and compared against the documented baseline in METRICS.md.

Assumptions
-----------
- Runs on the same machine as the live assistant (same models, same threads).
- E2E here means: 16 kHz utterance arrives -> ASR -> first LLM token -> full
  LLM response -> first TTS audio chunk ready. Playback/VAE onset is excluded
  because no audio hardware is used.
- Audio is generated by Piper itself, so ASR sees clean synthesized speech.

Tradeoffs
---------
Generating the ASR audio with Piper makes results repeatable but flatters ASR
accuracy relative to real microphone speech.
"""

import json
import os
import platform
import statistics
import sys
import time

import numpy as np

from asr.whisper_asr import WhisperASR
from llm.local_llm import LocalLLM
from tts.piper_tts import PiperTTS

# Allow printing Devanagari (Hindi) results on consoles that default to cp1252.
try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

TARGET_RATE = 16000
LLM_PROMPTS = [
    "What is the capital of France?",
    "Tell me a short joke.",
    "What is machine learning?",
]

HI_PROMPT = "फ्रांस की राजधानी क्या है?"


def now():
    return time.perf_counter()


def resample_to_16k(audio, src_rate):
    """Linear-interpolation resampler (good enough for clean TTS audio)."""
    n_out = int(len(audio) * TARGET_RATE / src_rate)
    x_old = np.linspace(0.0, 1.0, len(audio), endpoint=False)
    x_new = np.linspace(0.0, 1.0, n_out, endpoint=False)
    return np.interp(x_new, x_old, audio).astype(np.float32)


def synthesize_full(tts, text):
    """Concatenate all Piper chunks for `text` into one float32 array."""
    chunks = []
    for audio, sr in tts.synthesize_chunks(text):
        chunks.append(audio)
    return np.concatenate(chunks), sr


def run_llm_bench(llm, results):
    results["llm"] = {}
    try:
        t0 = now()
        llm.warmup()
        results["llm"]["warmup_time_s"] = round(now() - t0, 3)

        first_tokens, tok_per_s, tokens_total = [], [], []
        for prompt in LLM_PROMPTS:
            llm.reset_history()
            t0 = now()
            stream = llm.generate_stream(prompt, None, None)
            first = None
            n = 0
            for tok in stream:
                if first is None:
                    first = now()
                n += 1
            t1 = now()
            if first is not None and t1 > first:
                tok_per_s.append(n / (t1 - first))
            first_tokens.append(first - t0)
            tokens_total.append(n)

        results["llm"]["first_token_s"] = {
            "mean": round(statistics.mean(first_tokens), 3),
            "values_s": [round(v, 3) for v in first_tokens],
        }
        results["llm"]["tokens_per_sec"] = {
            "mean": round(statistics.mean(tok_per_s), 1),
            "values": [round(v, 1) for v in tok_per_s],
        }
        results["llm"]["tokens_per_prompt"] = tokens_total
    except Exception as e:
        results["llm"]["error"] = str(e)
    return results


def run_asr_bench(asr, audio_en, results):
    results["asr"] = {}
    try:
        # worst case: let Whisper auto-detect internally on the first call
        t0 = now()
        text, lang = asr.transcribe(audio_en, language=None, return_language=True)
        cold = now() - t0
        results["asr"]["cold_autodetect_s"] = round(cold, 3)
        results["asr"]["first_text"] = text
        results["asr"]["first_lang"] = lang

        # app path: explicit detect_language + transcribe with that language
        warm_times, detect_times = [], []
        for _ in range(3):
            t0 = now()
            dl, conf = asr.detect_language(audio_en)
            detect_times.append(now() - t0)
            t0 = now()
            asr.transcribe(audio_en, language=dl)
            warm_times.append(now() - t0)
        results["asr"]["detect_language_ms"] = {
            "mean": round(statistics.mean(detect_times) * 1000, 1),
            "values": [round(v * 1000, 1) for v in detect_times],
        }
        results["asr"]["transcribe_warm_mean_s"] = round(statistics.mean(warm_times), 3)
        results["asr"]["warm_values_s"] = [round(v, 3) for v in warm_times]
        results["asr"]["audio_seconds"] = round(len(audio_en) / TARGET_RATE, 2)
    except Exception as e:
        results["asr"]["error"] = str(e)
    return results


def run_tts_bench(tts, text, label, results):
    key = f"tts_{label}"
    results[key] = {}
    try:
        audio, sr = synthesize_full(tts, text)
        audio_seconds = len(audio) / sr

        synth_times = []
        for _ in range(3):
            t0 = now()
            for _ in tts.synthesize_chunks(text):
                pass
            synth_times.append(now() - t0)

        rtf = [t / audio_seconds for t in synth_times]
        results[key] = {
            "text": text,
            "audio_seconds": round(audio_seconds, 3),
            "sample_rate": sr,
            "synth_mean_s": round(statistics.mean(synth_times), 3),
            "synth_values_s": [round(v, 3) for v in synth_times],
            "rtf": {
                "mean": round(statistics.mean(rtf), 3),
                "values": [round(v, 3) for v in rtf],
            },
        }
    except Exception as e:
        results[key]["error"] = str(e)
    return results


def run_e2e(asr, llm, tts, audio_16k, label, results):
    key = f"e2e_{label}"
    results[key] = {}
    try:
        # 1) ASR: language detection + transcription, mirroring main.py's app
        #    path (both passes are part of what the user waits on).
        t0 = now()
        dl, conf = asr.detect_language(audio_16k)
        text, lang, _ = asr.transcribe(audio_16k, language=dl, return_stats=True)
        t_asr = now()

        # 2) LLM streaming: first token + full response
        llm.reset_history()
        stream = llm.generate_stream(text, None, None)
        first = None
        tokens = []
        for tok in stream:
            if first is None:
                first = now()
            tokens.append(tok)
        t_llm = now()
        response = "".join(tokens).strip()

        # 3) TTS: first chunk + total synthesis time
        first_tts = None
        total_samples = 0
        t_tts0 = now()
        for audio, sr in tts.synthesize_chunks(response):
            if first_tts is None:
                first_tts = now()
            total_samples += len(audio)
        t_tts = now()

        results[key] = {
            "transcript": text,
            "detected_lang": lang,
            "response": response,
            "asr_s": round(t_asr - t0, 3),
            "llm_first_token_s": round(first - t_asr, 3),
            "llm_total_s": round(t_llm - t_asr, 3),
            "tts_first_chunk_s": round(first_tts - t_llm, 3),
            "tts_total_s": round(t_tts - t_tts0, 3),
            "audio_to_first_llm_token_s": round(first - t0, 3),
            "audio_to_first_tts_s": round(first_tts - t0, 3),
            "total_pipeline_s": round(t_tts - t0, 3),
            "tokens": len(tokens),
        }
    except Exception as e:
        results[key]["error"] = str(e)
    return results


def main():
    print("=" * 70)
    print("  AZMTH Voice Assistant - Offline Pipeline Benchmark")
    print(f"  Python {platform.python_version()} | {platform.platform()} | "
          f"{os.cpu_count()} logical CPUs")
    print("=" * 70)

    results = {"environment": {
        "python": platform.python_version(),
        "platform": platform.platform(),
        "cpu_count": os.cpu_count(),
    }}

    print("\n[1/4] Loading models...")
    t0 = now()
    asr = WhisperASR("small")
    t_asr_load = now() - t0
    t0 = now()
    llm = LocalLLM()
    t_llm_load = now() - t0
    tts_en = PiperTTS("tts/en_US-lessac-medium.onnx")
    tts_hi = PiperTTS("tts/hi_IN-priyamvada-medium.onnx")
    results["model_load_times_s"] = {
        "asr": round(t_asr_load, 1),
        "llm": round(t_llm_load, 1),
        "tts_en": round(now() - t0, 1),
    }
    print(f"  ASR loaded in {t_asr_load:.1f}s | LLM in {t_llm_load:.1f}s")

    print("\n[2/4] Generating synthetic utterances with Piper...")
    en_audio, en_sr = synthesize_full(tts_en, "What is the capital of France?")
    en_16k = resample_to_16k(en_audio, en_sr)
    hi_audio, hi_sr = synthesize_full(tts_hi, HI_PROMPT)
    hi_16k = resample_to_16k(hi_audio, hi_sr)
    print(f"  EN utterance: {len(en_16k)/TARGET_RATE:.2f}s | "
          f"HI utterance: {len(hi_16k)/TARGET_RATE:.2f}s")

    print("\n[3/4] Running per-stage benchmarks...")
    results = run_asr_bench(asr, en_16k, results)
    results = run_llm_bench(llm, results)
    results = run_tts_bench(tts_en, "Hello, how are you today?", "en", results)
    results = run_tts_bench(tts_hi, HI_PROMPT, "hi", results)

    print("\n[4/4] Running end-to-end pipeline benchmark...")
    results = run_e2e(asr, llm, tts_en, en_16k, "en", results)
    results = run_e2e(asr, llm, tts_hi, hi_16k, "hi", results)

    with open("benchmark_results.json", "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2, ensure_ascii=False)

    print("\n" + "=" * 70)
    print("  RESULTS (also written to benchmark_results.json)")
    print("=" * 70)

    for key in ("asr", "llm", "tts_en", "tts_hi", "e2e_en", "e2e_hi"):
        block = results.get(key)
        if not block:
            continue
        print(f"\n[{key}]")
        for k, v in block.items():
            if isinstance(v, (int, float)):
                print(f"  {k}: {v}")
            elif isinstance(v, str):
                print(f"  {k}: {v}")
            elif isinstance(v, dict) and "mean" in v:
                print(f"  {k}: mean={v['mean']} values={v.get('values') or v.get('values_s')}")

    print("\nDone.")


if __name__ == "__main__":
    main()
